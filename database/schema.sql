CREATE TABLE IF NOT EXISTS customers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(150) NOT NULL,
    address VARCHAR(300) NOT NULL,
    customer_type VARCHAR(20) NOT NULL,
    employed BOOLEAN NOT NULL,
    employer_name VARCHAR(150),
    employer_address VARCHAR(300)
);

CREATE TABLE IF NOT EXISTS users (
    username VARCHAR(80) PRIMARY KEY,
    password_hash VARCHAR(300) NOT NULL,
    role VARCHAR(20) NOT NULL,
    customer_id BIGINT,
    CONSTRAINT fk_user_customer FOREIGN KEY(customer_id) REFERENCES customers(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS accounts (
    account_number VARCHAR(24) PRIMARY KEY,
    customer_id BIGINT NOT NULL,
    account_type VARCHAR(20) NOT NULL,
    branch VARCHAR(100) NOT NULL,
    balance DECIMAL(19,2) NOT NULL CHECK(balance >= 0),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT fk_account_customer FOREIGN KEY(customer_id) REFERENCES customers(id) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_number VARCHAR(24) NOT NULL,
    transaction_type VARCHAR(30) NOT NULL,
    amount DECIMAL(19,2) NOT NULL,
    balance_after DECIMAL(19,2) NOT NULL,
    occurred_at TIMESTAMP NOT NULL,
    description VARCHAR(300),
    CONSTRAINT fk_transaction_account FOREIGN KEY(account_number) REFERENCES accounts(account_number) ON DELETE CASCADE
);

CREATE TABLE IF NOT EXISTS interest_runs (
    month_key VARCHAR(7) PRIMARY KEY,
    completed_at TIMESTAMP NOT NULL
);
