import java.nio.file.Files;
import java.nio.file.Paths;
import java.sql.Connection;
import java.sql.DriverManager;
import java.sql.SQLException;
import java.sql.Statement;

public final class Database {
    @FunctionalInterface
    public interface SqlWork<T> { T run(Connection connection) throws Exception; }

    private final String jdbcUrl;

    public Database() {
        this(System.getProperty("banking.jdbc.url", "jdbc:h2:file:./data/banking;DB_CLOSE_DELAY=-1"));
    }

    public Database(String jdbcUrl) { this.jdbcUrl = jdbcUrl; }
    public String getJdbcUrl() { return jdbcUrl; }

    public void initialize() throws SQLException {
        if (jdbcUrl.startsWith("jdbc:h2:file:")) {
            try { Files.createDirectories(Paths.get("data")); }
            catch (Exception ex) { throw new SQLException("Could not create the database folder.", ex); }
        }
        withConnection(connection -> {
            String[] statements = {
                "CREATE TABLE IF NOT EXISTS customers (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, name VARCHAR(150) NOT NULL, address VARCHAR(300) NOT NULL, customer_type VARCHAR(20) NOT NULL, employed BOOLEAN NOT NULL, employer_name VARCHAR(150), employer_address VARCHAR(300))",
                "CREATE TABLE IF NOT EXISTS users (username VARCHAR(80) PRIMARY KEY, password_hash VARCHAR(300) NOT NULL, role VARCHAR(20) NOT NULL, customer_id BIGINT, CONSTRAINT fk_user_customer FOREIGN KEY(customer_id) REFERENCES customers(id) ON DELETE CASCADE)",
                "CREATE TABLE IF NOT EXISTS accounts (account_number VARCHAR(24) PRIMARY KEY, customer_id BIGINT NOT NULL, account_type VARCHAR(20) NOT NULL, branch VARCHAR(100) NOT NULL, balance DECIMAL(19,2) NOT NULL CHECK(balance >= 0), created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP, CONSTRAINT fk_account_customer FOREIGN KEY(customer_id) REFERENCES customers(id) ON DELETE CASCADE)",
                "CREATE TABLE IF NOT EXISTS transactions (id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, account_number VARCHAR(24) NOT NULL, transaction_type VARCHAR(30) NOT NULL, amount DECIMAL(19,2) NOT NULL, balance_after DECIMAL(19,2) NOT NULL, occurred_at TIMESTAMP NOT NULL, description VARCHAR(300), CONSTRAINT fk_transaction_account FOREIGN KEY(account_number) REFERENCES accounts(account_number) ON DELETE CASCADE)",
                "CREATE TABLE IF NOT EXISTS interest_runs (month_key VARCHAR(7) PRIMARY KEY, completed_at TIMESTAMP NOT NULL)"
            };
            try (Statement statement = connection.createStatement()) {
                for (String sql : statements) statement.execute(sql);
            }
            return null;
        });
    }

    public Connection getConnection() throws SQLException { return DriverManager.getConnection(jdbcUrl); }

    public <T> T withConnection(SqlWork<T> work) throws SQLException {
        try (Connection connection = getConnection()) { return work.run(connection); }
        catch (SQLException ex) { throw ex; }
        catch (Exception ex) { throw new SQLException(ex.getMessage(), ex); }
    }

    public <T> T inTransaction(SqlWork<T> work) throws SQLException {
        try (Connection connection = getConnection()) {
            connection.setAutoCommit(false);
            try {
                T value = work.run(connection);
                connection.commit();
                return value;
            } catch (Exception ex) {
                try { connection.rollback(); } catch (SQLException rollbackError) { ex.addSuppressed(rollbackError); }
                if (ex instanceof SQLException) throw (SQLException) ex;
                if (ex instanceof RuntimeException) throw (RuntimeException) ex;
                throw new SQLException(ex.getMessage(), ex);
            }
        }
    }
}
